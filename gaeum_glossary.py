def lookup(q):
    """질문 속 낱말로 설명 항목 하나 → (제목, 설명) · 없으면 None. 앞에서부터(구체적인 것 먼저)."""
    tq = _t(q)
    for words, title, body in ENTRIES:
        if any(_t(w) in tq for w in words):
            return title, body
    return None
