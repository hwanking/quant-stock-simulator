    print("=" * 74)
    fail_out = []
    for cls, st in sorted(fail_stats.items(), key=lambda kv: kv[1]['loss']):
        print(f"  {cls:<32} {st['n']:>4}건 · 누적손실 {st['loss']:+9.1f}%p")
        fail_out.append({'class': cls, 'n': st['n'], 'total_loss': round(st['loss'], 1)})

