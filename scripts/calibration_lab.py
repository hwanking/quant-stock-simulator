#: 과거 기준일 — 20영업일(판정 지평)보다 넓은 25봉 간격으로 떼어 표본 중복을 줄인다
def make_asof_dates(prices_df, n_dates, horizon=20, spacing=25,
                    forward_from=None):
    """기준일 후보. `forward_from` 이 있으면 **전방 구간만 촘촘히** 뽑는다.

    ■ 왜 전방만은 촘촘해야 하는가 (라운드 78)
      평소 25봉 간격은 표본 중복을 줄이려는 것이다. 그런데 전방 구간은
      길이가 45거래일뿐이라 25봉 간격으로 뽑으면 **날짜가 2개**가 된다.
      R55 는 국면 라우팅이고 국면은 시장 수준 변수라 **날짜가 표본**이다
      — 날짜 2개로는 라우팅을 평가할 수 없다. 그래서 전방은 전부 쓴다.

      촘촘한 표본은 서로 상관된다. 그건 숨기지 않고 **에피소드 기준**
      (같은 종목 35일 묶음, R64 §3 정의)으로 병기해 해결한다.

      `usable` 상한이 이미 horizon 을 빼 두므로, 아직 20봉이 지나지
      않은 날짜는 여기서 자동으로 빠진다 — 채점 못 할 날을 만들지 않는다.
    """
    dates = list(prices_df['trade_date'].astype(str))
    # 마지막 판정도 채점 가능해야 하므로 horizon 봉 이전에서 끊는다
    usable = dates[260:len(dates) - horizon - 1]
    if forward_from:
        return sorted(d for d in usable if d >= forward_from)
    picked = usable[::-spacing][:n_dates]     # 최근에서 과거로 spacing 간격
    return sorted(picked)


def load_universe(eng, top, existing):
    """시총 상위 `top` 종목 목록 — **한 번만 받아 캐시에 박제한다.**

    ■ 왜 캐시가 필수인가 (라운드 72)
      샤드를 6개 띄웠더니 여섯이 각자 3,014종목 유니버스를 중복으로
      받아 왔다. 느린 것도 문제지만 **분할이 깨진다** — 시총 순위는
      장중에 바뀌므로 샤드마다 pool 순서가 달라지면 `k % n` 이 같은
      종목을 두 번 돌리거나 아예 빠뜨린다. 분할이 성립하려면 모든
      워커가 **같은 목록**을 봐야 한다.

      그래서 목록을 파일에 박제하고 샤드는 그것만 읽는다. 다시 받고
      싶으면 캐시 파일을 지운다.
    """
    cache = os.path.join(PROJ, '.portfolio', f'universe_top{top}.json')
    if os.path.exists(cache):
        with open(cache, encoding='utf-8') as f:
            meta = json.load(f)
        syms = meta.get('symbols') or []
        add = [s for s in syms if s not in existing]
        print(f"유니버스 캐시 사용 ({meta.get('made')}, 전 종목 "
              f"{meta.get('total')}) → 신규 {len(add):,}종목")
        return add
    try:
        uni = eng.get_screener_universe(full_market=True, max_pages=40)
    except Exception as exc:                                   # noqa: BLE001
        # 못 넓혔으면 **밝힌다.** 조용히 기존 목록으로 도는 것은
        # "넓혔다"는 착각을 준다 (§3).
        print(f"유니버스 수집 실패 — 넓히지 못했다: "
              f"{type(exc).__name__}: {exc}")
        return []
    syms = [u['symbol'] for u in uni[:top]]
    with open(cache, 'w', encoding='utf-8') as f:
        json.dump(dict(made=datetime.date.today().isoformat(), top=top,
                       total=len(uni), symbols=syms,
                       note='샤드가 같은 분할을 보도록 박제한 목록. '
                            '다시 받으려면 이 파일을 지운다.'),
                  f, ensure_ascii=False)
    add = [s for s in syms if s not in existing]
    print(f"유니버스 수집: 전 종목 {len(uni):,} 중 시총 상위 {top:,} → "
          f"신규 {len(add):,}종목 · 캐시 저장 {os.path.basename(cache)}")
    return add


